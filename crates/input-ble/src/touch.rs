//! Upstream d80d659af53188c45d3d2966f86ec35c0849287f; report ID changed to 2
//! so the existing keyboard can retain report ID 1.
const FINGER_MAP: &[u8] = &[
    0x05, 0x0d, 0x09, 0x04, 0xa1, 0x01, 0x85, 0x02, 0x09, 0x22, 0xa1, 0x02, 0x09, 0x42, 0x09, 0x47,
    0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x02, 0x81, 0x02, 0x75, 0x01, 0x95, 0x06, 0x81, 0x03,
    0x09, 0x51, 0x15, 0x00, 0x25, 0x7f, 0x75, 0x08, 0x95, 0x01, 0x81, 0x02, 0x05, 0x01, 0x09, 0x01,
    0xa1, 0x00, 0x09, 0x30, 0x09, 0x31, 0x16, 0x00, 0x00, 0x26, 0x10, 0x27, 0x36, 0x00, 0x00, 0x46,
    0x10, 0x27, 0x66, 0x00, 0x00, 0x75, 0x10, 0x95, 0x02, 0x81, 0x02, 0xc0, 0xc0, 0xc0,
];
pub(crate) fn report_map() -> Vec<u8> {
    let mut map = Vec::with_capacity(47 + FINGER_MAP.len());
    map.extend_from_slice(&super::REPORT_MAP[..47]);
    map.extend_from_slice(FINGER_MAP);
    map
}
pub(crate) fn report(down: bool, x: i32, y: i32) -> [u8; 6] {
    let x = (x.clamp(0, 10000) as u16).to_le_bytes();
    let y = (y.clamp(0, 10000) as u16).to_le_bytes();
    [if down { 3 } else { 2 }, 0, x[0], x[1], y[0], y[1]]
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn contact_and_release_keep_absolute_position_and_confidence() {
        assert_eq!(report(true, 5000, 2500), [3, 0, 0x88, 0x13, 0xc4, 0x09]);
        assert_eq!(report(false, 5000, 2500), [2, 0, 0x88, 0x13, 0xc4, 0x09]);
        assert_eq!(report(true, -1, i32::MAX), [3, 0, 0, 0, 0x10, 0x27]);
    }
}
